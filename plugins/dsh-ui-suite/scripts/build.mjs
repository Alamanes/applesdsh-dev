/**
 * dsh-ui-suite build.
 *
 * Each component is its own package (`dsh-ui-copy`, `dsh-ui-identity`, …), and
 * each of them ships one browser bundle: the shared runtime, its own component,
 * and the loader wrapper. The runtime lives once, in `dsh-ui-copy/src/core/`,
 * and is inlined into every package that needs it — a package must work when it
 * is installed alone, so it cannot import a sibling at runtime.
 *
 * Stylesheet-only components (`dsh-ui-ask`, `-composer`, `-menu`, `-sidebar`)
 * need no build: their host half reads the CSS from disk on every render.
 *
 * Usage:
 *   node scripts/build.mjs            rebuild every package's lib/client.js
 *   node scripts/build.mjs --check    fail when a checked-in bundle is stale
 *   node scripts/build.mjs verify     run the contract checks
 */

import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SUITE = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PLUGINS = resolve(SUITE, '..')
const RUNTIME = join(PLUGINS, 'dsh-ui-copy', 'src', 'core', 'runtime.js')

/** Package -> component key. The browser bundle is built for these only. */
const JS_PACKAGES = {
  'dsh-ui-copy': 'copy',
  'dsh-ui-identity': 'identity',
  'dsh-ui-session-delete': 'session-delete',
  'dsh-ui-peak-valley': 'peak-valley',
  'dsh-ui-status-phrases': 'status-phrases',
  'dsh-ui-foot-panels': 'foot-panels',
  'dsh-ui-restart': 'restart',
  'dsh-ui-quota': 'quota',
  'dsh-ui-effort-slider': 'effort-slider',
  'dsh-ui-whale': 'whale',
  'dsh-ui-skill-explorer': 'skill-explorer',
  'dsh-ui-theme': 'theme',
}

/** `dsh-ui-session-delete` -> `SESSION_DELETE`, the injected global's suffix. */
function envOf(key) {
  return key.replace(/-/g, '_').toUpperCase()
}

function factoryOf(key) {
  return 'dshuiComponent_' + key.replace(/-/g, '_')
}

function bundle(pkg, key) {
  const runtime = readFileSync(RUNTIME, 'utf8').trimEnd()
  const component = readFileSync(join(PLUGINS, pkg, 'src', 'component.js'), 'utf8').trimEnd()
  const factory = factoryOf(key)
  const env = envOf(key)

  if (!component.includes(`function ${factory}(`)) {
    throw new Error(`${pkg}/src/component.js: expected \`function ${factory}(rt)\``)
  }

  return `/**
 * ${pkg} browser half — generated by dsh-ui-suite/scripts/build.mjs.
 *
 * One component per package: the runtime below is the same code every suite
 * package carries, so installing this package alone works, and the component
 * mounts under the same failure boundary as the rest of the suite.
 *
 * Edit src/component.js (or the runtime in dsh-ui-copy/src/core), then rerun
 * the build.
 */

${runtime}

/* ---- component -------------------------------------------------------- */

${component}

/* ---- entry ------------------------------------------------------------ */

window.__ModuleLoader__.load({
  // The boot-graph row id is the package name; client-modules serves this file
  // at \`/plugins/<包名>/client.js\` and keys the factory by the same string.
  id: '${pkg}',
  factory: (require) => {
    const module = { exports: {} }
    const exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })

    /**
     * Mount this package's component on its own runtime.
     *
     * The host half injects this row's configuration as \`window.DSHUI_${env}\`
     * before the boot graph runs, because a boot-graph row arrives as
     * \`{ id, url, rev }\` and \`apply(ctx, config)\` always sees an empty config.
     */
    function apply(ctx) {
      const injected = window.DSHUI_${env}
      const config = typeof injected === 'object' && injected !== null ? injected : {}
      const runtime = dshuiCreateRuntime({ ctx, require }, { '${key}': config })
      runtime.mount('${key}', ${factory})
      exports.runtime = runtime
      return function dispose() {
        runtime.dispose()
      }
    }

    exports.apply = apply
    exports.inject = []
    return module.exports
  },
})
`
}

function main() {
  const mode = process.argv[2]
  let stale = 0

  for (const [pkg, key] of Object.entries(JS_PACKAGES)) {
    const target = join(PLUGINS, pkg, 'lib', 'client.js')
    const built = bundle(pkg, key)
    const current = existsSync(target) ? readFileSync(target, 'utf8') : ''

    if (mode === '--check') {
      if (current !== built) {
        console.error(`${pkg}: lib/client.js is stale`)
        stale += 1
      }
      continue
    }
    if (current !== built) {
      writeFileSync(target, built)
      console.log(`${pkg}: ${built.length} bytes`)
    }
  }

  if (mode === '--check') {
    if (stale > 0) {
      console.error(`\n${stale} package(s) need a rebuild: node scripts/build.mjs`)
      process.exit(1)
    }
    console.log(`${Object.keys(JS_PACKAGES).length} bundles up to date`)
  }
}

main()
