/**
 * dsh-ui-copy client bundler.
 *
 * The client bundle is one file because `dsh-client-modules` resolves exactly
 * one browser entry per package (`exports["./client"]`); a subpath entry can
 * carry a host half but never a second browser module. So the sources in
 * `src/` are concatenated into `lib/client.js` in a fixed order:
 *
 *   src/core/runtime.js          the runtime, once
 *   src/components/<nn>-<key>.js one function per component, ordered by prefix
 *   src/core/entry.js            the loader wrapper and the registry
 *
 * `src/core/entry.js` is the last file and receives a `__COMPONENTS__`
 * placeholder that this script replaces with the registry table, so the order
 * of `src/components/` is the order components mount in.
 *
 * Every source file is plain script — no import, no export — because the output
 * is a single classic script wrapped by the loader. Component files must define
 * exactly one top-level function named `dshuiComponent_<key>`, where `<key>` is
 * the file name with the numeric prefix removed.
 *
 * Usage: `node scripts/build.mjs` (also `--check` to verify a checked-in
 * `lib/client.js` matches its sources).
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CORE = join(ROOT, 'src', 'core')
const COMPONENTS = join(ROOT, 'src', 'components')
const OUTPUT = join(ROOT, 'lib', 'client.js')

const HEADER = `/**
 * dsh-ui-copy browser half — generated by scripts/build.mjs, do not edit by hand.
 *
 * One bundle, one loader row, one MutationObserver. Every component below is a
 * top-level \`dshuiComponent_<key>\` function registered in the table at the end
 * of this file; each one reads \`--dshui-*\` tokens from lib/styles/tokens.css and
 * is switchable through the profile's \`ui-copy\` config.
 *
 * Edit \`src/\`, then run \`node scripts/build.mjs\`.
 */

`

/** `10-copy.js` -> `copy`; the prefix is mount order only. */
function keyOf(file) {
  return file.replace(/^\d+[-_]/, '').replace(/\.js$/, '')
}

function read(path) {
  return readFileSync(path, 'utf8')
}

function componentFiles() {
  const files = readdirSync(COMPONENTS).filter((file) => file.endsWith('.js'))
  // Filename order is mount order, and the numeric prefix is a number, not a
  // string: `90-` mounts before `100-`.
  const prefix = (file) => {
    const match = /^(\d+)/.exec(file)
    return match === null ? Number.MAX_SAFE_INTEGER : Number(match[1])
  }
  return files.sort((left, right) => prefix(left) - prefix(right) || left.localeCompare(right))
}

/** Fail loudly on a component file that does not expose its expected factory. */
function verifyComponent(file, source) {
  const key = keyOf(file)
  const expected = `dshuiComponent_${key.replace(/-/g, '_')}`
  if (!source.includes(`function ${expected}(`)) {
    throw new Error(`${file}: expected a top-level \`function ${expected}(rt)\``)
  }
  if (/^\s*(import|export)\s/m.test(source)) {
    throw new Error(`${file}: component sources must be plain script, not ESM`)
  }
  return { key, name: expected, file }
}

function bundle() {
  const files = componentFiles()
  const components = files.map((file) => verifyComponent(file, read(join(COMPONENTS, file))))

  const runtime = read(join(CORE, 'runtime.js'))
  const entry = read(join(CORE, 'entry.js'))
  const bodies = files.map((file) => {
    const source = read(join(COMPONENTS, file)).trimEnd()
    return `/* ---- ${file} ${'-'.repeat(Math.max(1, 66 - file.length))} */\n\n${source}`
  })

  const table = components
    .map(({ key, name }) => `      ['${key}', ${name}],`)
    .join('\n')

  const assembled = [
    HEADER + runtime.trimEnd(),
    ...bodies,
    entry.replace('      __COMPONENTS__', table).trimEnd(),
    '',
  ].join('\n\n')

  const meta = components.map(({ key, file }) => ` *   ${key.padEnd(16)} ${file}`).join('\n')
  return assembled.replace(' * __COMPONENT_TABLE__', meta)
}

const built = bundle()
const mode = process.argv[2]
if (mode === '--check') {
  let current = ''
  try {
    current = read(OUTPUT)
  } catch {
    current = ''
  }
  if (current !== built) {
    console.error('lib/client.js is stale; run `node scripts/build.mjs`')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
} else {
  writeFileSync(OUTPUT, built)
  console.log(`wrote ${OUTPUT} (${built.length} bytes)`)
}
